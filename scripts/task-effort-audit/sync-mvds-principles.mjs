#!/usr/bin/env node
/*
 * Refresh the MVDS principle catalog the audit validates tags against.
 *
 * MVDS owns its principles (beckharrisdesign/mvds, principles.config.mjs). The
 * published package doesn't ship them, so the audit keeps a committed snapshot
 * (mvds-principles.json) stamped with the MVDS commit it came from. Tags in task
 * files must resolve against this snapshot, or the task is rejected.
 *
 *   node scripts/task-effort-audit/sync-mvds-principles.mjs                 # from GitHub main
 *   node scripts/task-effort-audit/sync-mvds-principles.mjs --from <file>   # from a local manifest-snapshot.json
 *
 * Reads only. Never writes to the MVDS repo.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export const SOURCE_URL = 'https://raw.githubusercontent.com/beckharrisdesign/mvds/main/src/generated/manifest-snapshot.json';
const OUT = fileURLToPath(new URL('./mvds-principles.json', import.meta.url));

/** Keep only what the audit needs; the snapshot's other fields stay in MVDS. */
export function toCatalog(snapshot, origin, now = new Date()) {
  if (!Array.isArray(snapshot?.principles)) throw new Error('not an MVDS manifest snapshot: no principles array');
  return {
    about: 'Generated by sync-mvds-principles.mjs from the MVDS manifest snapshot. Do not edit by hand; re-run the sync.',
    origin,
    mvdsCommit: snapshot.commit ?? null,
    mvdsGeneratedAt: snapshot.generatedAt ?? null,
    syncedAt: now.toISOString(),
    principles: snapshot.principles.map((p) => ({
      id: p.id,
      title: p.title,
      description: p.description,
      checkKind: p.checkKind,
      enforcement: p.enforcement,
      source: p.source,
    })),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf('--from');
  const from = i >= 0 ? process.argv[i + 1] : null;
  let snapshot;
  if (from) snapshot = JSON.parse(await readFile(from, 'utf8'));
  else {
    const res = await fetch(SOURCE_URL);
    if (!res.ok) throw new Error(`fetch ${SOURCE_URL} → HTTP ${res.status}`);
    snapshot = await res.json();
  }
  const catalog = toCatalog(snapshot, from ?? SOURCE_URL);
  await writeFile(OUT, `${JSON.stringify(catalog, null, 2)}\n`);
  const guiding = catalog.principles.filter((p) => p.checkKind === 'guiding').length;
  console.log(`wrote ${catalog.principles.length} principles (${guiding} guiding) from MVDS ${catalog.mvdsCommit ?? '(commit unknown)'}`);
}
