// The DMC thread chart — the single source of truth for thread color in
// this experiment. Decoded from the Wolfram `DMC-Thread-Colors` dataset
// (JonMcLoone), which is also what the Figma DMC variable library is
// generated from, so a color authored in Figma and a color named here are
// the same value. Nearest-match against a *different* transcription of the
// chart misnames threads with high confidence, so don't mix tables.
//
// `family` groups threads the way the DMC palette poster does. It is derived
// from the thread name, not the color, so it follows DMC's own vocabulary.

export type DmcFamily =
  | "Reds"
  | "Pinks"
  | "Oranges"
  | "Yellows"
  | "Greens"
  | "Blues"
  | "Purples"
  | "Browns & Neutrals"
  | "Grays & Black/White";

export interface DmcThread {
  /** DMC article number, e.g. "310" — or "White", "Ecru", "B5200". */
  id: string;
  /** DMC's own color name, e.g. "Coral Medium". */
  name: string;
  /** Normalized #rrggbb, lowercase. Unique across the chart. */
  hex: string;
  family: DmcFamily;
}

